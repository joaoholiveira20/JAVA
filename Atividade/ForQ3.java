public class ForQ3 {
    public static void main(String[] args) {
        for (int i = 1;i<=51;i++){
            if (i % 2 !=0){
                System.out.println("Números Impares: "+i);
            }
        }
        for (int ip = 52;ip<=100;ip++){
            if (ip % 2 ==0){
                System.out.println("Números Pares: "+ip);
            }
    }
}
}
